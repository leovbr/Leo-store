-- LEOOSTORE account marketplace table
-- Run this once in Supabase Dashboard > SQL Editor.
create table if not exists public.store_accounts (
  id bigint generated by default as identity primary key,
  account_name text not null,
  game_name text not null,
  description text not null default '',
  price bigint not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  warranty_days integer not null default 30 check (warranty_days >= 0),
  image1_url text not null,
  image2_url text not null,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.store_accounts enable row level security;
grant select on public.store_accounts to anon, authenticated;
grant insert, update, delete on public.store_accounts to authenticated;
drop policy if exists "Public can read active account listings" on public.store_accounts;
create policy "Public can read active account listings" on public.store_accounts
for select to anon, authenticated using (is_active = true or auth.uid() = '3939553f-ef8d-4295-8f2f-39c86ce9ed20'::uuid);
drop policy if exists "Only LEOOSTORE admin can insert accounts" on public.store_accounts;
create policy "Only LEOOSTORE admin can insert accounts" on public.store_accounts
for insert to authenticated with check (auth.uid() = '3939553f-ef8d-4295-8f2f-39c86ce9ed20'::uuid);
drop policy if exists "Only LEOOSTORE admin can update accounts" on public.store_accounts;
create policy "Only LEOOSTORE admin can update accounts" on public.store_accounts
for update to authenticated using (auth.uid() = '3939553f-ef8d-4295-8f2f-39c86ce9ed20'::uuid) with check (auth.uid() = '3939553f-ef8d-4295-8f2f-39c86ce9ed20'::uuid);
drop policy if exists "Only LEOOSTORE admin can delete accounts" on public.store_accounts;
create policy "Only LEOOSTORE admin can delete accounts" on public.store_accounts
for delete to authenticated using (auth.uid() = '3939553f-ef8d-4295-8f2f-39c86ce9ed20'::uuid);
grant usage, select on sequence public.store_accounts_id_seq to authenticated;
